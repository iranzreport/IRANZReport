export function playerKey(p) {
  return ((p.first || '') + '_' + (p.last || '')).toLowerCase().replace(/[^a-z0-9]/g, '_');
}

export function sessionKey(courseId) {
  const id = courseId || 'default';
  return 'session_' + id.trim().toLowerCase().replace(/[^a-z0-9]+/g, '_');
}

export function encodeEval(name) {
  return name.replace(/[.#$/[]\s]/g, '_');
}

export function decodeEval(encoded) {
  const known = Object.keys(EVAL_COLORS);
  for (const n of known) if (encodeEval(n) === encoded) return n;
  return encoded.replace(/_/g, ' ');
}

export function getEvalColor(name, i = 0) {
  return EVAL_COLORS[name] || ['#22c55e', '#38bdf8', '#f59e0b', '#a78bfa', '#fb923c', '#f472b6'][i % 6];
}

export function scoreColor(v) {
  const n = parseFloat(v);
  if (n >= 4.5) return '#22c55e';
  if (n >= 3.5) return '#38bdf8';
  if (n >= 2.5) return '#facc15';
  if (n >= 1.5) return '#f59e0b';
  return '#ef4444';
}

export function isCoachCourse(courseId) {
  return courseId === 'advanced_coaches';
}
